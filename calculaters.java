    private void equalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_equalActionPerformed
                                           
num2=Double.parseDouble(tex1.getText());
switch(operator){
    case "+":
        resalt=num1+num2;
        break;
        case "-":
        resalt=num1-num2;
        break;
        case "*":
        resalt=num1*num2;
        break;
        case "/":
            if(num2==0){
                tex1.setText("Error");
                return;
            }
        resalt=num1/num2;
        break;
        
}
tex1.setText(String.valueOf(resalt));
    }//GEN-LAST:event_equalActionPerformed

